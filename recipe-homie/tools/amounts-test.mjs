/**
 * 单位换算单元测试（ITERATION-0.5 W0）：锁定「两钱 / 斤两 / 约耗 / 约重 / 括号净重 / 断裂 / 半角括号」
 * 这些已知形态的正确折算。背景：门禁 E1–E3 确认现有两道闸门只验公式一致性、验不出输入错误
 * （「X两Y钱」841 行 stored 全错仍 PASS）——本文件就是那道缺失的输入侧回归表。
 *
 * 口径：市制十两制 1斤=500g、1两=50g、1钱=5g、1分=0.5g（1959 年后）。
 * 用法：node tools/amounts-test.mjs   （或 npm run test:amounts）
 */
import { parseAmount } from "../src/ingredients.ts";
import { toGrams, splitIngredient } from "../src/parse.ts";

let pass = 0;
let fail = 0;
const fails = [];
function eq(actual, expected, label) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) pass++;
  else { fail++; fails.push(`${label}: 得 ${a} 应 ${e}`); }
}
const g = (amount, entry) => parseAmount(amount, entry).grams;

// ---- 1. 「X两Y钱」汉字复合（E3 实测 825/825 错、stored==bug 841 行的形态）----
eq(g("二两三钱"), 115, "二两三钱");
eq(g("一两五钱"), 75, "一两五钱");
eq(g("二两五钱"), 125, "二两五钱");
eq(g("一两二钱"), 60, "一两二钱");
eq(g("三两五钱"), 175, "三两五钱");
eq(g("一两三钱"), 65, "一两三钱");
eq(g("九两九钱"), 495, "九两九钱（边界）");
eq(g("一两"), 50, "一两（单段不回归）");
eq(g("三钱"), 15, "三钱（单段不回归）");
eq(g("二两三钱"), toGrams("二两三钱") ?? -1, "parseAmount 与 toGrams 两处病灶同值");

// ---- 2. 「X斤Y两」复合与回归（0.4 已全对，不许修坏）----
eq(g("二斤五两"), 1250, "二斤五两");
eq(g("一斤六两"), 800, "一斤六两");
eq(g("四斤五两"), 2250, "四斤五两");
eq(g("三斤"), 1500, "三斤");
eq(g("十二两"), 600, "十二两");

// ---- 3. 「半」尾巴 ----
eq(g("一两半"), 75, "一两半");
eq(g("一斤半"), 750, "一斤半");
eq(g("二斤半"), 1250, "二斤半");
eq(g("半斤"), 250, "半斤");

// ---- 4. 「两」当数字（2）的独立形态 ----
eq(g("两斤"), 1000, "两斤");
eq(g("两钱"), 10, "两钱");
eq(g("两斤半"), 1250, "两斤半");

// ---- 5. 阿拉伯数字（0.4 已全对 214 条，不许修坏）----
eq(g("2两3钱"), 115, "2两3钱");
eq(g("1两5钱"), 75, "1两5钱");
eq(g("25两"), 1250, "25两");
eq(g("2斤5两"), 1250, "2斤5两");

// ---- 5b. 外层小数（W2 P3：南北实测「1.5钱/2.5斤」4 行；守卫拦 OCR 压行噪声）----
eq(g("1.5钱"), 7.5, "1.5钱（外层小数）");
eq(g("2.5斤"), 1250, "2.5斤（外层小数）");
eq(g("2.5斤（实耗3两）"), 1250, "2.5斤（实耗3两）");
eq(g("446.2钱"), 10, "446.2钱（OCR 噪声：多 digit 小数不认，落回尾段「2钱」口径）");
eq(g("1斤2两"), 600, "1斤2两（阿拉伯复合不受守卫影响）");

// ---- 6. 区间形态不误伤（「三、四朵」不折成 34 朵；连写「三四钱」仍按区间跳过）----
eq(parseAmount("三、四朵").count, 4, "三、四朵 count");
eq(parseAmount("三、四朵").grams, null, "三、四朵 grams");
eq(parseAmount("三四朵").count, 4, "三四朵 count");
eq(toGrams("三四钱"), null, "toGrams 三四钱（区间守卫）");
eq(g("三四钱"), 20, "parseAmount 三四钱（现状：无守卫、取尾字折 4 钱；W0 不改此口径）");

// ---- 7. 约耗括号：整锅质量才是入库值，括号里的附着量不许顶掉 ----
eq(g("二斤（约耗二两）"), 1000, "二斤（约耗二两）");
eq(g("半斤(约耗五钱)"), 250, "半斤(约耗五钱)（半角）");
eq(g("一斤(约耗一两半)"), 500, "一斤(约耗一两半)（半角）");
eq(g("二两一钱(约耗五分)"), 105, "二两一钱(约耗五分)（半角）");
eq(toGrams("二斤（约耗二两）"), 1000, "toGrams 约耗");

// ---- 8. 约重括号：括号质量就是真实重量 ----
eq(g("一条（约重一斤半）"), 750, "一条（约重一斤半）");
eq(g("一条(约重一斤三两)"), 650, "一条(约重一斤三两)（半角，E3 抽取失败形态）");
eq(g("一只（约重七两）"), 350, "一只（约重七两）");

// ---- 9. 括号净重（无「约重」字样）：个数 + 括号净重按括号折，覆盖默认单重 ----
eq(g("一个（四斤）"), 2000, "一个（四斤）");
eq(g("一个（四斤）", { unitGrams: 1500 }), 2000, "一个（四斤）覆盖 unitGrams=1500（E2 Q7 应 2000）");
eq(g("一只(二钱)"), 10, "一只(二钱)（半角净重）");
eq(parseAmount("一个（四斤）").count, 1, "一个（四斤）count 保留");
eq(g("二只（每个二两）"), null, "二只（每个二两）不误当整条净重");
eq(g("半只（约一斤半）"), 750, "半只（约一斤半）（约X 半尾巴）");
eq(g("（约七两半）五只"), 375, "（约七两半）五只（括号前置形态）");
eq(g("1副（约3.5斤）"), 1750, "1副（约3.5斤）（阿拉伯小数）");
eq(g("1付（重2斤）"), 1000, "1付（重2斤）（「重」字形态）");
eq(g("1尾（1斤5两）"), 750, "1尾（1斤5两）（括号内复合）");
eq(g("一段（七两）"), 350, "一段（七两）");
eq(g("一两二分"), 51, "一两二分（两分形态）");
eq(g("二两三分"), 101.5, "二两三分");

// ---- 10. 名称/分量断裂（E2 Q6：斤段吞进原料名，49 条）----
{
  const r = splitIngredient("肉清汤一斤六两");
  eq(r.name, "肉清汤", "断裂：肉清汤 名称");
  eq(r.amount, "一斤六两", "断裂：肉清汤 分量");
  eq(r.grams, 800, "断裂：肉清汤 800g（0.4 存 300）");
}
eq(splitIngredient("鸡汤……二斤三两").grams, 1150, "断裂：鸡汤……二斤三两（0.4 存 150）");
eq(splitIngredient("白糖四斤五两").grams, 2250, "断裂：白糖四斤五两（0.4 存 250）");
eq(splitIngredient("花生油一斤五两（约耗一两）").grams, 750, "断裂+约耗：花生油一斤五两（约耗一两）");
eq(splitIngredient("肉清汤$\\textcircled{1}$一斤六两").grams, 800, "断裂带 OCR 脚注符");

// ---- 11. 半角括号形态（E3：抽取失败 → 整道 kcal=16 的浙江-073）----
{
  const r = splitIngredient("鲜黄鱼一条(约重一斤三两)");
  eq(r.name, "鲜黄鱼", "半角括号：鲜黄鱼 名称");
  eq(r.grams, 650, "半角括号：鲜黄鱼 650g（0.4 为 null）");
}
eq(splitIngredient("花生油一斤(约耗一两半)").name, "花生油", "半角括号：花生油 名称（0.4 整串当名）");
eq(splitIngredient("花生油一斤(约耗一两半)").grams, 500, "半角括号：花生油 500g（0.4 为 null）");

// ---- 12. 全角形态不回归（0.4 已对）----
eq(splitIngredient("猪油一斤").grams, 500, "全角单段粘连不回归");
eq(splitIngredient("子鸡一只（约重二斤）").grams, 1000, "全角个数+约重不回归");
eq(splitIngredient("鸡蛋 四只").count, 4, "空格拆分不回归");
eq(splitIngredient("肥膘二两").grams, 100, "全角二两不回归");

console.log(`amounts-test：${pass} 过 / ${fail} 败`);
if (fail) {
  console.log(fails.map((x) => `  FAIL ${x}`).join("\n"));
  process.exitCode = 1;
}
